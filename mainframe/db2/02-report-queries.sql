-- Category-wise approved expense total
SELECT CATEGORY_CD, COUNT(*) AS TXN_COUNT, SUM(AMOUNT) AS TOTAL_AMOUNT
FROM EXPENSE_TXN
WHERE STATUS = 'A'
GROUP BY CATEGORY_CD
ORDER BY CATEGORY_CD;

-- Monthly approved expense summary
SELECT YEAR(EXPENSE_DATE) AS EXPENSE_YEAR,
       MONTH(EXPENSE_DATE) AS EXPENSE_MONTH,
       COUNT(*) AS TXN_COUNT,
       SUM(AMOUNT) AS TOTAL_AMOUNT
FROM EXPENSE_TXN
WHERE STATUS = 'A'
GROUP BY YEAR(EXPENSE_DATE), MONTH(EXPENSE_DATE)
ORDER BY EXPENSE_YEAR, EXPENSE_MONTH;
