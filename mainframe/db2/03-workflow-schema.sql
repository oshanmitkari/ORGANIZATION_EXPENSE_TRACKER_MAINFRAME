-- Illustrative Db2 for z/OS workflow schema. Review object ownership and storage at the target site.
CREATE TABLE DEPARTMENT (
    DEPARTMENT_ID CHAR(8) NOT NULL,
    DEPARTMENT_NAME VARCHAR(80) NOT NULL,
    ACTIVE_FLAG CHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    PRIMARY KEY (DEPARTMENT_ID),
    UNIQUE (DEPARTMENT_NAME)
);

CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID CHAR(8) NOT NULL,
    EMPLOYEE_NAME VARCHAR(80) NOT NULL,
    DEPARTMENT_ID CHAR(8) NOT NULL,
    DESIGNATION VARCHAR(60) NOT NULL,
    MANAGER_ID CHAR(8),
    COST_CENTRE CHAR(12) NOT NULL,
    EMPLOYMENT_STATUS CHAR(1) NOT NULL CHECK (EMPLOYMENT_STATUS IN ('A','I')),
    PRIMARY KEY (EMPLOYEE_ID),
    FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENT(DEPARTMENT_ID),
    FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE TABLE EXPENSE_CATEGORY (
    CATEGORY_CODE CHAR(4) NOT NULL,
    CATEGORY_NAME VARCHAR(40) NOT NULL,
    ACTIVE_FLAG CHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    PRIMARY KEY (CATEGORY_CODE), UNIQUE (CATEGORY_NAME)
);

CREATE TABLE EXPENSE (
    EXPENSE_ID CHAR(16) NOT NULL,
    TRANSACTION_ID CHAR(12) NOT NULL,
    EMPLOYEE_ID CHAR(8) NOT NULL,
    EXPENSE_DATE DATE NOT NULL,
    CATEGORY_CODE CHAR(4) NOT NULL,
    AMOUNT DECIMAL(9,2) NOT NULL CHECK (AMOUNT > 0),
    CURRENCY_CODE CHAR(3) NOT NULL DEFAULT 'INR',
    DESCRIPTION VARCHAR(39) NOT NULL,
    COST_CENTRE CHAR(12) NOT NULL,
    REFERENCE_ID VARCHAR(30),
    STATUS VARCHAR(24) NOT NULL CHECK (STATUS IN ('Draft','Submitted','Pending approval','Approved','Rejected','Posted','Reconciliation exception')),
    CREATED_TS TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    UPDATED_TS TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (EXPENSE_ID), UNIQUE (TRANSACTION_ID),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID),
    FOREIGN KEY (CATEGORY_CODE) REFERENCES EXPENSE_CATEGORY(CATEGORY_CODE)
);

CREATE TABLE APPROVAL_HISTORY (
    APPROVAL_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY,
    EXPENSE_ID CHAR(16) NOT NULL,
    ACTOR_ID CHAR(8) NOT NULL,
    ACTION_CODE VARCHAR(16) NOT NULL CHECK (ACTION_CODE IN ('SUBMIT','APPROVE','REJECT','POST')),
    COMMENT_TEXT VARCHAR(500),
    EVENT_TS TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (APPROVAL_ID),
    FOREIGN KEY (EXPENSE_ID) REFERENCES EXPENSE(EXPENSE_ID),
    FOREIGN KEY (ACTOR_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE TABLE POSTING_LEDGER (
    TRANSACTION_ID CHAR(12) NOT NULL,
    EXPENSE_ID CHAR(16) NOT NULL,
    POSTED_AMOUNT DECIMAL(9,2) NOT NULL CHECK (POSTED_AMOUNT > 0),
    CURRENCY_CODE CHAR(3) NOT NULL,
    COST_CENTRE CHAR(12) NOT NULL,
    POSTED_TS TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    RUN_ID CHAR(24),
    PRIMARY KEY (TRANSACTION_ID),
    UNIQUE (EXPENSE_ID),
    FOREIGN KEY (EXPENSE_ID) REFERENCES EXPENSE(EXPENSE_ID)
);

CREATE TABLE BATCH_RUN (
    RUN_ID CHAR(24) NOT NULL,
    JOB_NAME VARCHAR(32) NOT NULL,
    RUN_STATUS VARCHAR(16) NOT NULL CHECK (RUN_STATUS IN ('SUBMITTED','RUNNING','COMPLETED','WARNING','FAILED')),
    SUBMITTED_TS TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    COMPLETED_TS TIMESTAMP,
    INPUT_COUNT INTEGER NOT NULL DEFAULT 0,
    OUTPUT_COUNT INTEGER NOT NULL DEFAULT 0,
    DUPLICATE_COUNT INTEGER NOT NULL DEFAULT 0,
    REJECTED_COUNT INTEGER NOT NULL DEFAULT 0,
    POSTED_COUNT INTEGER NOT NULL DEFAULT 0,
    RETURN_CODE SMALLINT,
    ERROR_SUMMARY VARCHAR(500),
    PRIMARY KEY (RUN_ID)
);

CREATE TABLE BATCH_TRANSACTION (
    RUN_ID CHAR(24) NOT NULL,
    TRANSACTION_ID CHAR(12) NOT NULL,
    PROCESS_STATUS VARCHAR(16) NOT NULL CHECK (PROCESS_STATUS IN ('ACCEPTED','DUPLICATE','REJECTED','POSTED','PENDING')),
    REASON_CODE CHAR(8),
    EXPENSE_ID CHAR(16),
    PRIMARY KEY (RUN_ID, TRANSACTION_ID),
    FOREIGN KEY (RUN_ID) REFERENCES BATCH_RUN(RUN_ID),
    FOREIGN KEY (EXPENSE_ID) REFERENCES EXPENSE(EXPENSE_ID)
);

ALTER TABLE POSTING_LEDGER
    ADD CONSTRAINT FK_POST_LEDGER_RUN
    FOREIGN KEY (RUN_ID) REFERENCES BATCH_RUN(RUN_ID);

CREATE TABLE AUDIT_EVENT (
    EVENT_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY,
    ACTOR_ID CHAR(8),
    ACTION_CODE VARCHAR(32) NOT NULL,
    ENTITY_TYPE VARCHAR(24) NOT NULL,
    ENTITY_ID VARCHAR(32) NOT NULL,
    OUTCOME VARCHAR(16) NOT NULL,
    CORRELATION_ID CHAR(24),
    EVENT_TS TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (EVENT_ID)
);

CREATE TABLE RECONCILIATION (
    RUN_ID CHAR(24) NOT NULL,
    SOURCE_COUNT INTEGER NOT NULL,
    DUPLICATE_COUNT INTEGER NOT NULL,
    REJECTED_COUNT INTEGER NOT NULL,
    POSTED_COUNT INTEGER NOT NULL,
    PENDING_COUNT INTEGER NOT NULL,
    RECON_STATUS VARCHAR(12) NOT NULL CHECK (RECON_STATUS IN ('MATCHED','MISMATCH')),
    PRIMARY KEY (RUN_ID),
    FOREIGN KEY (RUN_ID) REFERENCES BATCH_RUN(RUN_ID)
);

CREATE INDEX IX_EXPENSE_EMP_DATE ON EXPENSE (EMPLOYEE_ID, EXPENSE_DATE);
CREATE INDEX IX_EXPENSE_STATUS_DATE ON EXPENSE (STATUS, EXPENSE_DATE);
CREATE INDEX IX_EXPENSE_DEPT_STATUS ON EXPENSE (COST_CENTRE, STATUS);
CREATE INDEX IX_APPROVAL_EXPENSE_TS ON APPROVAL_HISTORY (EXPENSE_ID, EVENT_TS);
CREATE INDEX IX_BATCH_STATUS_TS ON BATCH_RUN (RUN_STATUS, SUBMITTED_TS);
CREATE INDEX IX_AUDIT_ENTITY_TS ON AUDIT_EVENT (ENTITY_TYPE, ENTITY_ID, EVENT_TS);
