CREATE TABLE EXPENSE_TXN (
    TXN_ID       CHAR(12)      NOT NULL,
    EMP_ID       CHAR(8)       NOT NULL,
    EXPENSE_DATE DATE          NOT NULL,
    CATEGORY_CD  CHAR(4)       NOT NULL,
    AMOUNT       DECIMAL(9,2)  NOT NULL CHECK (AMOUNT > 0),
    DESCRIPTION  VARCHAR(39),
    STATUS       CHAR(1)       NOT NULL DEFAULT 'P',
    CREATED_TS   TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (TXN_ID)
);

CREATE TABLE EMPLOYEE_MASTER (
    EMP_ID       CHAR(8)      NOT NULL PRIMARY KEY,
    EMP_NAME     VARCHAR(52)  NOT NULL,
    ACTIVE_FLAG  CHAR(1)      NOT NULL DEFAULT 'Y'
);

CREATE INDEX IX_EXPENSE_DATE ON EXPENSE_TXN (EXPENSE_DATE);
CREATE INDEX IX_EXPENSE_EMP_CAT ON EXPENSE_TXN (EMP_ID, CATEGORY_CD);
