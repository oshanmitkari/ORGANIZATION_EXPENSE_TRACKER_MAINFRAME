-- Employee transaction history, amount descending
SELECT E.EXPENSE_ID, E.TRANSACTION_ID, E.EXPENSE_DATE, C.CATEGORY_NAME,
       E.AMOUNT, E.CURRENCY_CODE, E.STATUS
FROM EXPENSE E
JOIN EXPENSE_CATEGORY C ON C.CATEGORY_CODE = E.CATEGORY_CODE
WHERE E.EMPLOYEE_ID = ?
  AND E.EXPENSE_DATE BETWEEN ? AND ?
ORDER BY E.AMOUNT DESC, E.EXPENSE_DATE DESC;

-- Department/cost-centre totals by status
SELECT D.DEPARTMENT_ID, D.DEPARTMENT_NAME, E.STATUS,
       COUNT(*) AS RECORD_COUNT, SUM(E.AMOUNT) AS TOTAL_AMOUNT
FROM EXPENSE E
JOIN EMPLOYEE P ON P.EMPLOYEE_ID = E.EMPLOYEE_ID
JOIN DEPARTMENT D ON D.DEPARTMENT_ID = P.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_ID, D.DEPARTMENT_NAME, E.STATUS
ORDER BY D.DEPARTMENT_NAME, E.STATUS;

-- Monthly total for financial postings only
SELECT YEAR(POSTED_TS) AS POST_YEAR, MONTH(POSTED_TS) AS POST_MONTH,
       COUNT(*) AS POST_COUNT, SUM(POSTED_AMOUNT) AS POSTED_TOTAL
FROM POSTING_LEDGER
GROUP BY YEAR(POSTED_TS), MONTH(POSTED_TS)
ORDER BY POST_YEAR, POST_MONTH;

-- Pending approvals
SELECT E.EXPENSE_ID, E.EMPLOYEE_ID, P.MANAGER_ID, E.EXPENSE_DATE,
       E.CATEGORY_CODE, E.AMOUNT, E.CURRENCY_CODE
FROM EXPENSE E
JOIN EMPLOYEE P ON P.EMPLOYEE_ID = E.EMPLOYEE_ID
WHERE E.STATUS = 'Pending approval'
ORDER BY E.EXPENSE_DATE, E.EXPENSE_ID;

-- Approved versus rejected amounts; posted is reported separately below
SELECT STATUS, COUNT(*) AS RECORD_COUNT, SUM(AMOUNT) AS TOTAL_AMOUNT
FROM EXPENSE
WHERE STATUS IN ('Approved', 'Rejected')
GROUP BY STATUS;

-- Potential business-key duplicates in the submitted expense population
SELECT EMPLOYEE_ID, EXPENSE_DATE, CATEGORY_CODE, AMOUNT, DESCRIPTION,
       COUNT(*) AS DUPLICATE_COUNT
FROM EXPENSE
WHERE STATUS <> 'Rejected'
GROUP BY EMPLOYEE_ID, EXPENSE_DATE, CATEGORY_CODE, AMOUNT, DESCRIPTION
HAVING COUNT(*) > 1
ORDER BY DUPLICATE_COUNT DESC, EMPLOYEE_ID, EXPENSE_DATE;

-- Batch rejects and exception detail
SELECT T.RUN_ID, T.TRANSACTION_ID, T.REASON_CODE, T.EXPENSE_ID,
       R.RUN_STATUS, R.SUBMITTED_TS, R.ERROR_SUMMARY
FROM BATCH_TRANSACTION T
JOIN BATCH_RUN R ON R.RUN_ID = T.RUN_ID
WHERE T.PROCESS_STATUS = 'REJECTED'
ORDER BY R.SUBMITTED_TS DESC, T.RUN_ID, T.TRANSACTION_ID;

-- Failed or warning batch executions
SELECT RUN_ID, JOB_NAME, RUN_STATUS, SUBMITTED_TS, COMPLETED_TS,
       INPUT_COUNT, OUTPUT_COUNT, DUPLICATE_COUNT, REJECTED_COUNT,
       POSTED_COUNT, RETURN_CODE, ERROR_SUMMARY
FROM BATCH_RUN
WHERE RUN_STATUS IN ('FAILED','WARNING')
ORDER BY SUBMITTED_TS DESC;

-- Reconciliation totals
SELECT R.RUN_ID, R.SOURCE_COUNT, R.DUPLICATE_COUNT, R.REJECTED_COUNT,
       R.POSTED_COUNT, R.PENDING_COUNT, R.RECON_STATUS,
       B.RETURN_CODE, B.ERROR_SUMMARY
FROM RECONCILIATION R
JOIN BATCH_RUN B ON B.RUN_ID = R.RUN_ID
ORDER BY B.SUBMITTED_TS DESC;
